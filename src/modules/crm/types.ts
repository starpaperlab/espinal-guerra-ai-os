import type { stages } from "./schema";
export type Brand = { id: string; slug: string; name: string };
export type Contact = {
  id: string;
  name: string;
  company: string;
  email: string;
  phone: string;
  notes: string;
  tags: string[];
};
export type Lead = {
  id: string;
  organization_id: string;
  brand_id: string;
  contact_id: string;
  contact: Contact;
  source: string;
  campaign: string;
  service: string;
  need: string;
  budget: string;
  urgency: string;
  score: number | null;
  classification: string | null;
  stage: keyof typeof stages;
  owner_id: string | null;
  next_action: string;
  follow_up_at: string | null;
  ai_problem: string;
  ai_opportunity: string;
  ai_recommendation: string;
  evaluated_at: string | null;
  captured_at: string;
  is_test: boolean;
};
export type Opportunity = {
  id: string;
  brand_id: string;
  lead_id: string;
  service: string;
  estimated_value: number;
  currency: string;
  stage: keyof typeof stages;
  probability: number;
  expected_close: string | null;
  next_action: string;
  closed_value: number | null;
  updated_at: string;
  is_test: boolean;
};
export type Activity = {
  id: string;
  lead_id: string;
  brand_id: string;
  kind: string;
  title: string;
  notes: string;
  due_at: string | null;
  completed_at: string | null;
  is_test: boolean;
};
export type Proposal = {
  id: string;
  title: string;
  amount: number;
  currency: string;
  status: string;
  issued_at: string | null;
  valid_until: string | null;
};
export type History = {
  id: number;
  entity_type: string;
  action: string;
  actor_id: string | null;
  changed_at: string;
  before_data: Record<string, unknown> | null;
  after_data: Record<string, unknown>;
};
export type Summary = {
  leads: number;
  new: number;
  hot: number;
  warm: number;
  cold: number;
  open: number;
  follow_ups: number;
  sent: number;
  won: number;
  won_value: Record<string, number>;
};
export type CrmData = {
  now: string;
  brands: Brand[];
  selectedBrand?: Brand;
  summary: Summary | null;
  leads: Lead[];
  leadCount: number;
  opportunities: Opportunity[];
  opportunityCount: number;
  activities: Activity[];
  followUpLeads: Lead[];
  followUpCount: number;
  activityCount: number;
  detail: Lead | null;
  detailActivities: Activity[];
  detailOpportunities: Opportunity[];
  proposals: Proposal[];
  history: History[];
  historyCount: number;
  error?: string;
  page: number;
  query: Record<string, string>;
  userId: string;
};
