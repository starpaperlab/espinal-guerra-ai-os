import { readFile, writeFile } from "node:fs/promises";
const files = [
  "integrations/n8n/prepare-crm-request.cjs",
  "integrations/n8n/normalized-lead.cjs",
];
const helpers = (await Promise.all(files.map((f) => readFile(f, "utf8")))).map(
  (code) =>
    code.replace(
      /\nif \(typeof module !== "undefined"\)\s*module\.exports(?:\.\w+)?\s*=\s*[^;]+;/g,
      "",
    ),
);
const wrapper = `
// n8n Code node: Run Once for All Items. No secret values belong in this artifact.
const mode = $env.CRM_CAPTURE_IS_TEST;
if (mode !== 'true' && mode !== 'false') throw new Error('CRM_TEST_MODE_REQUIRED');
const observedAt = $now.toISO();
return $input.all().map((item, index) => ({
  json: prepareCrmRequest(normalizeN8nLead(item.json, {
    workflow_id: $workflow.id, execution_id: $execution.id, item_index: index,
    brand_id: $env.CRM_BRAND_ID || undefined, capture_source_key: item.json.capture_source_key || $env.CRM_CAPTURE_SOURCE_KEY || undefined, observed_at: observedAt, is_test: mode === 'true', execution_mode: $execution.mode || 'unknown'
  }), $env.CRM_WEBHOOK_SECRET)
}));
`;
const content =
  "// GENERATED by npm run build:n8n. Edit the source helpers, not this file.\n" +
  helpers.join("\n") +
  wrapper;
const target = "integrations/n8n/prepare-normalized-code-node.js.txt";
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== content)
    throw new Error("N8N_CODE_ARTIFACT_STALE");
} else await writeFile(target, content);
